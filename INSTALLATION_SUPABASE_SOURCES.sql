-- Stockage central des sources ELT. À exécuter dans Supabase > SQL Editor.
-- Bucket privé : accès uniquement via le client serveur de Streamlit.
insert into storage.buckets (id, name, public, file_size_limit)
values ('elt-sources', 'elt-sources', false, 104857600)
on conflict (id) do update set public = false, file_size_limit = 104857600;

create table if not exists public.journal_modifications_sources (
    id bigint generated by default as identity primary key,
    cree_le timestamptz not null default now(),
    utilisateur text not null default 'Administrateur',
    source text not null,
    feuille text,
    operation text not null,
    nombre_lignes integer,
    details jsonb not null default '{}'::jsonb
);

alter table public.journal_modifications_sources enable row level security;
grant all on table public.journal_modifications_sources to service_role;
grant usage, select on sequence public.journal_modifications_sources_id_seq to service_role;

